def _sub(text: str, m: dict[str, str]) -> str:
    for k, v in m.items():
        text = text.replace(f"@@{k}@@", v)
    return text

def create_world(name: str, description: str = "", *, force: bool = False) -> str:
    if not _NAME_RE.match(name):
        raise ScaffoldError(f"world name '{name}' invalid: 2-25 chars, lowercase, start with letter")
    target = os.path.join(WORLDS_DIR, name)
    if os.path.exists(target) and not force:
        raise ScaffoldError(f"{target} already exists (force=True to overwrite)")
    kind = f"{name}.signal_game"
    cap = "".join(p.capitalize() for p in name.split("_"))
    mapping = {"NAME": name, "KIND": kind, "CAP": cap,
               "DESC": description.replace('"', "'") or f"{name} world",
               "DATE": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
               "GRAPH": f"cogym-{name}"}
    os.makedirs(target, exist_ok=True)
    for fname, tmpl in [("__init__.py", MANIFEST_PY), ("manifest.json", MANIFEST),
                        ("world.py", WORLD_PY), ("README.md", README_MD), ("AGENTS.md", AGENTS_MD)]:
        with open(os.path.join(target, fname), "w") as fh:
            fh.write(_sub(tmpl, mapping))
    print(json.dumps({"created": target, "kind": kind}, indent=2))
    return target

def main(argv=None):
    argv = argv if argv is not None else sys.argv[1:]
    if not argv:
        print(__doc__); return 1
    create_world(argv[0], argv[1] if len(argv) > 1 else "")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
